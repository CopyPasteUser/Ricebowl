# --------------------------------------------------------------------------- raster helpers


def _pillow():
    from PIL import Image, ImageChops, ImageDraw, ImageFilter
    return Image, ImageChops, ImageDraw, ImageFilter


def _lerp(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(len(a)))


def _vertical_gradient(width, height, stops):
    """stops: [(position 0..1, (r, g, b)), ...]"""
    Image, _chops, ImageDraw, _filter = _pillow()
    image = Image.new("RGB", (width, height))
    draw = ImageDraw.Draw(image)
    for y in range(height):
        t = y / max(1, height - 1)
        for (p0, c0), (p1, c1) in zip(stops, stops[1:]):
            if t <= p1 or (p1, c1) == stops[-1]:
                u = 0.0 if p1 == p0 else min(1.0, max(0.0, (t - p0) / (p1 - p0)))
                draw.line((0, y, width, y), fill=tuple(round(v) for v in _lerp(c0, c1, u)))
                break
    return image


def _grain(image, seed, amplitude=2):
    """Deterministic +-amplitude dither so large gradients do not band after JPEG."""
    Image, ImageChops, _draw, _filter = _pillow()
    data = random.Random(seed).randbytes(image.width * image.height)
    noise = Image.frombytes("L", image.size, data).point(
        lambda v: 128 + (v - 128) * amplitude // 128)
    noise = Image.merge("RGB", (noise, noise, noise))
    return ImageChops.add(image, noise, scale=1.0, offset=-128)


def ten_wallpaper(variant: str = "blue"):
    """Bowl of light: a bowl at the lower left third, rays and ripples rising from its rim."""
    Image, _chops, ImageDraw, ImageFilter = _pillow()
    if variant not in ("blue", "midnight"):
        raise ValueError(variant)
    strength = 1.0 if variant == "blue" else 0.67
    top, bottom = ((2, 21, 64), (4, 63, 126)) if variant == "blue" else ((2, 11, 34), (8, 28, 71))
    base = _vertical_gradient(W, H, [(0, top), (1, bottom)]).convert("RGBA")
    ox, oy = 760, 868  # centre of the bowl rim

    rays = Image.new("RGBA", (W, H), (40, 160, 252, 0))
    draw = ImageDraw.Draw(rays)
    for angle, spread, alpha in ((-62, 7, 26), (-44, 5, 32), (-26, 9, 38), (-8, 6, 42),
                                 (10, 8, 42), (28, 6, 38), (46, 9, 32), (64, 6, 26)):
        left, right = math.radians(angle - spread), math.radians(angle + spread)
        reach = 1800
        draw.polygon([(ox, oy),
                      (ox + reach * math.sin(left), oy - reach * math.cos(left)),
                      (ox + reach * math.sin(right), oy - reach * math.cos(right))],
                     fill=(40, 160, 252, int(alpha * 1.7 * strength)))
    base = Image.alpha_composite(base, rays.filter(ImageFilter.GaussianBlur(20)))

    glow = Image.new("RGBA", (W, H), (28, 145, 239, 0))
    gd = ImageDraw.Draw(glow)
    gd.ellipse((ox - 700, oy - 520, ox + 700, oy + 380), fill=(28, 145, 239, int(70 * strength)))
    gd.ellipse((ox - 330, oy - 240, ox + 330, oy + 150), fill=(113, 214, 255, int(88 * strength)))
    base = Image.alpha_composite(base, glow.filter(ImageFilter.GaussianBlur(110)))

    ripples = Image.new("RGBA", (W, H), (120, 215, 255, 0))
    rd = ImageDraw.Draw(ripples)
    for rx, ry, alpha in ((480, 150, 62), (690, 225, 44), (920, 305, 30), (1170, 395, 20),
                          (1450, 490, 13)):
        rd.ellipse((ox - rx, oy - ry, ox + rx, oy + ry), outline=(120, 215, 255, int(alpha * strength)),
                   width=3)
    base = Image.alpha_composite(base, ripples.filter(ImageFilter.GaussianBlur(1.2)))

    # The bowl itself, drawn at 2x and reduced for clean edges.
    scale = 2
    bowl = Image.new("RGBA", (W * scale, H * scale))
    bd = ImageDraw.Draw(bowl)

    def s(*values):
        return tuple(int(v * scale) for v in values)

    body = (14, 86, 160) if variant == "blue" else (9, 55, 112)
    foot = (8, 52, 112) if variant == "blue" else (5, 32, 78)
    bd.pieslice(s(ox - 190, oy - 130, ox + 190, oy + 130), 0, 180, fill=body + (255,))
    bd.pieslice(s(ox - 150, oy - 95, ox + 150, oy + 95), 0, 180, fill=(22, 118, 196, 255)
                if variant == "blue" else (13, 76, 140, 255))
    bd.ellipse(s(ox - 190, oy - 13, ox + 190, oy + 13), fill=(150, 226, 255, 255))
    bd.ellipse(s(ox - 170, oy - 7, ox + 170, oy + 9), fill=(214, 246, 255, 255))
    bd.rounded_rectangle(s(ox - 60, oy + 124, ox + 60, oy + 142), radius=9 * scale, fill=foot + (255,))
    bowl = bowl.resize((W, H), Image.LANCZOS)
    base = Image.alpha_composite(base, bowl)
    return _grain(base.convert("RGB"), seed=10 if variant == "blue" else 11)


def luna_hills():
    """Terraced rice hills at dusk: five receding ridges, streak clouds and a low sun."""
    Image, _chops, ImageDraw, ImageFilter = _pillow()
    scale = 2
    w, h = W * scale, H * scale

    sky = _vertical_gradient(w, h, [
        (0.00, (22, 78, 150)), (0.30, (70, 150, 210)), (0.52, (150, 212, 232)),
        (0.62, (255, 233, 178)), (1.00, (255, 214, 150))]).convert("RGBA")

    glow = Image.new("RGBA", (w, h), (255, 232, 170, 0))
    gd = ImageDraw.Draw(glow)
    sx, sy = 540 * scale, 585 * scale
    for reach in (1000, 800, 620, 460, 330):  # nested, so the glow falls off smoothly
        gd.ellipse((sx - reach * scale, sy - int(reach * .6) * scale,
                    sx + reach * scale, sy + int(reach * .6) * scale), fill=(255, 226, 160, 26))
    gd.ellipse((sx - 210 * scale, sy - 125 * scale, sx + 210 * scale, sy + 125 * scale),
               fill=(255, 244, 205, 150))
    sky = Image.alpha_composite(sky, glow.filter(ImageFilter.GaussianBlur(120 * scale)))
    sun = Image.new("RGBA", (w, h), (255, 250, 226, 0))
    ImageDraw.Draw(sun).ellipse((sx - 72 * scale, sy - 72 * scale, sx + 72 * scale, sy + 72 * scale),
                                fill=(255, 250, 226, 255))
    sky = Image.alpha_composite(sky, sun.filter(ImageFilter.GaussianBlur(2 * scale)))

    clouds = Image.new("RGBA", (w, h), (255, 240, 236, 0))
    cd = ImageDraw.Draw(clouds)
    for x, y, rx, ry, alpha in ((1330, 150, 520, 9, 150), (1500, 188, 360, 6, 120),
                                (1150, 232, 430, 8, 110), (1650, 262, 300, 5, 120),
                                (780, 330, 380, 7, 90), (1400, 370, 520, 8, 95),
                                (300, 120, 250, 5, 90), (1010, 445, 420, 6, 80)):
        cd.ellipse(((x - rx) * scale, (y - ry) * scale, (x + rx) * scale, (y + ry) * scale),
                   fill=(255, 240, 236, alpha))
    sky = Image.alpha_composite(sky, clouds.filter(ImageFilter.GaussianBlur(5 * scale)))

    # (baseline y, amplitude, waves [(wavelength, phase, weight)], top colour, bottom colour, terraces)
    layers = (
        (650, 46, ((900, 0.4, 1.0), (330, 2.1, 0.45), (170, 4.0, 0.2)), (118, 162, 190), (96, 148, 170), 0),
        (700, 58, ((1100, 2.6, 1.0), (420, 0.3, 0.5), (210, 5.2, 0.22)), (96, 156, 160), (72, 134, 142), 0),
        (775, 74, ((1300, 4.4, 1.0), (520, 1.0, 0.45), (260, 3.3, 0.2)), (84, 160, 112), (52, 126, 92), 14),
        (870, 92, ((1500, 1.7, 1.0), (610, 3.8, 0.4), (300, 0.7, 0.18)), (96, 176, 84), (40, 118, 62), 20),
        (990, 118, ((1700, 5.0, 1.0), (700, 2.2, 0.42), (350, 4.6, 0.15)), (112, 184, 70), (34, 100, 50), 30),
    )
    canvas = sky
    for number, (base, amplitude, waves, top, bottom, gap) in enumerate(layers):
        xs = range(0, w + 1, scale)

        def profile(x, base=base, amplitude=amplitude, waves=waves):
            u = x / scale
            total = sum(weight * math.sin(2 * math.pi * u / length + phase)
                        for length, phase, weight in waves)
            return (base - amplitude * 0.5 * (1 + total / 1.65)) * scale

        points = [(x, profile(x)) for x in xs]
        mask = Image.new("L", (w, h), 0)
        ImageDraw.Draw(mask).polygon(points + [(w, h), (0, h)], fill=255)
        top_y = int(min(y for _x, y in points))
        fill = _vertical_gradient(w, h - top_y, [(0, top), (1, bottom)]).convert("RGBA")
        layer = Image.new("RGBA", (w, h))
        layer.paste(fill, (0, top_y))
        if gap:
            lines = ImageDraw.Draw(layer, "RGBA")
            step = gap * scale
            for k in range(1, 60):
                shift = step * k * (1 + 0.035 * k)
                curve = [(x, y + shift) for x, y in points]
                if min(y for _x, y in curve) > h:
                    break
                lines.line(curve, fill=(255, 240, 170, 34), width=2 * scale)
                lines.line([(x, y + shift + 3 * scale) for x, y in curve],
                           fill=(10, 60, 40, 30), width=2 * scale)
        layer.putalpha(mask)
        rim = Image.new("RGBA", (w, h))
        ImageDraw.Draw(rim).line(points, fill=(255, 238, 190, 70), width=2 * scale)
        rim.putalpha(Image.composite(rim.getchannel("A"), Image.new("L", (w, h), 0), mask))
        canvas = Image.alpha_composite(canvas, layer)
        canvas = Image.alpha_composite(canvas, rim)
        if number < len(layers) - 1:  # warm mist between the ridges
            mist = Image.new("RGBA", (w, h), (255, 226, 170, 0))
            ImageDraw.Draw(mist).rectangle((0, int(base * scale), w, int((base + 60) * scale)),
                                           fill=(255, 226, 170, 38))
            canvas = Image.alpha_composite(canvas, mist.filter(ImageFilter.GaussianBlur(26 * scale)))
    final = canvas.convert("RGB").resize((W, H), Image.LANCZOS)
    return _grain(final, seed=21)


# --------------------------------------------------------------------------- write / check

SVG_FILES = {
    "assets/ten-start.svg": ten_start_svg,
    "assets/windows10-bloom.svg": windows10_bloom_svg,
    "assets/ricebowl-chrome-start.svg": chrome_start_svg,
}
# Icon-theme aliases that tests require to stay byte-identical to the start mark.
ALIASES = {
    "assets/ten-start.svg": [f"assets/icons/RiceHub-Ten-Penguin/scalable/apps/{n}.svg"
                             for n in ("start-here", "xfce4-menu", "ricehub-ten")],
    "assets/ricebowl-chrome-start.svg": [f"assets/icons/RiceHub-Chrome-Icons/scalable/apps/{n}.svg"
                                         for n in ("start-here", "xfce4-menu", "ricehub-start", "ricebowl-start")],
}
WALLPAPERS = {
    "assets/wallpapers/ten-blue.jpg": lambda: ten_wallpaper("blue"),
    "assets/wallpapers/ten-midnight.jpg": lambda: ten_wallpaper("midnight"),
    "assets/wallpapers/luna-hills.jpg": luna_hills,
}


def expected_svgs() -> dict[str, str]:
    out = {}
    for rel, builder in SVG_FILES.items():
        text = builder()
        out[rel] = text
        for alias in ALIASES.get(rel, ()):
            out[alias] = text
    return out


def write_all(root: Path = ROOT, *, wallpapers: bool = True) -> list[str]:
    written = []
    for rel, text in expected_svgs().items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        written.append(rel)
    if wallpapers:
        for rel, builder in WALLPAPERS.items():
            target = root / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            builder().save(target, "JPEG", quality=JPEG_QUALITY, optimize=True)
            written.append(rel)
    return written


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if a tracked SVG differs from the generator (JPEGs are not byte-compared)")
    parser.add_argument("--no-wallpapers", action="store_true")
    args = parser.parse_args(argv)
    if args.check:
        stale = [rel for rel, text in expected_svgs().items()
                 if not (ROOT / rel).is_file() or (ROOT / rel).read_text(encoding="utf-8") != text]
        for rel in stale:
            print("stale:", rel, file=sys.stderr)
        return 1 if stale else 0
    for rel in write_all(wallpapers=not args.no_wallpapers):
        print("wrote", rel)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
