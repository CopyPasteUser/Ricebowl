#!/usr/bin/env python3
"""Regenerate RiceBowl's original start marks and wallpapers (SG4 / WP4.5 RF01-RF03, RF06).

Everything here is drawn from first principles with fixed parameters: no
network access, no AI inference, no input photographs, no random seed other
than the constants below.  The artwork is original RiceBowl work licensed under
the repository's MIT licence (see LICENSE).  It deliberately does NOT reproduce
any operating system's logo, hero wallpaper or stock photograph:

* ``assets/ten-start.svg``            a glowing rice bowl with three rising light
                                      rays (no four-pane window mark)
* ``assets/windows10-bloom.svg``      the same bowl-of-light as a vector wallpaper:
                                      a fan of rays rising from a bowl, concentric
                                      ripples (not a lit window with side beams)
* ``assets/wallpapers/ten-blue.jpg``,
  ``assets/wallpapers/ten-midnight.jpg``
                                      raster version of the bowl-of-light scene
* ``assets/wallpapers/luna-hills.jpg``
                                      layered, terraced rice-hill ridges at dusk
                                      (many receding ridges, streak clouds and a
                                      low sun; not one hill under a cumulus sky)
* ``assets/ricebowl-chrome-start.svg``
                                      launcher circle with a bowl glyph in the
                                      RiceBowl Chrome-rice palette (not the Google
                                      brand colours)

The icon-theme aliases that must stay byte-identical to the start marks
(``start-here`` / ``xfce4-menu`` / ``ricehub-*``) are rewritten as well.

Pillow is a development-only dependency; JPEG bytes can differ between Pillow /
libjpeg builds, so tests compare decoded pixels, not file hashes.

    python3 scripts/build_original_artwork.py            # rewrite tracked files
    python3 scripts/build_original_artwork.py --check    # exit 1 if tracked SVGs differ
"""
